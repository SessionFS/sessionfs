"""Native per-tool marketplace catalogs (marketplace v2 §7.2-§7.4).

Pure and deterministic: turns a set of approved package versions (their
canonical package trees plus listing metadata) into the file tree of ONE
catalog git repository that each tool's own plugin installer can consume,
plus the per-plugin repositories Gemini CLI installs from, plus the L0
("static") works-in verdicts for every (version, tool) pair.

Every vendor key emitted here was checked against current vendor
documentation on 2026-10-20 (``VENDOR_SOURCES`` lists the pages). Nothing
unconfirmed is emitted. Keys deliberately NOT emitted because they could
not be confirmed are listed in ``UNCONFIRMED`` so the gap stays visible.

Repository layout::

    .claude-plugin/marketplace.json     Claude Code
    .github/plugin/marketplace.json     GitHub Copilot CLI (checked before
                                        .claude-plugin/ in its lookup order)
    .agents/plugins/marketplace.json    Codex
    .cursor-plugin/marketplace.json     Cursor (team marketplace import)
    plugins/<id>/                       one directory per plugin, shared by
                                        every tool:
        plugin.json                     Agent Plugins core (Codex and
                                        Copilot read it; name rewritten to <id>)
        .claude-plugin/plugin.json      Claude Code manifest
        .cursor-plugin/plugin.json      Cursor manifest
        gemini-extension.json           public scope only (Gemini installs a
                                        per-plugin repository, see below)
        skills/<skill>/SKILL.md ...     the package bytes, unchanged
    SESSIONFS-CATALOG.json              version ids, content hashes and
                                        projection hashes (supply-chain bind),
                                        plus every excluded version and why
    README.md

Failure isolation: each plugin is preflighted on its own (paths, file /
directory conflicts, the generated manifest names, per-plugin size). A
plugin that fails is EXCLUDED with a reason; it never fails the catalog.
The whole catalog also has a file and byte budget: plugins are admitted in
catalog order (namespace, name, version id) and one that would push the
catalog over either budget is excluded (``catalog_budget``) while later,
smaller ones may still fit. No single plugin may exceed
``max_plugin_bytes`` (``plugin_too_large``), and only admitted plugins are
charged to the budget. Exclusions are disclosed in
``SESSIONFS-CATALOG.json``.
"""

