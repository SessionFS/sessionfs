BUDGET_ORDER = "namespace, name, version_id"


class NativeFeedError(ValueError):
    """An input that can never be projected (never a partial catalog)."""


@dataclass(frozen=True)
class CatalogInput:
    """One approved package version, as the projection needs it."""

    version_id: str
    package_id: str
    namespace: str
    name: str
    description: str
    version_label: str | None
    content_hash: str
    published_at: datetime
    files: dict[str, bytes]
    license: str | None = None
    homepage: str | None = None
    publisher_name: str | None = None
    # Adapter-computed degradations (skill_package_versions.compatibility).
    omitted_components: tuple[str, ...] = ()
    # Set when the input could not be loaded (archive unavailable, input
    # byte budget): the version is excluded and disclosed, never projected.
    skip_reason: str | None = None


@dataclass
class ProjectedPlugin:
    plugin_id: str
    version_id: str
    package_id: str
    content_hash: str
    projection_hash: str
    plugin_path: str
    files: dict[str, bytes]
    tools: tuple[str, ...]


@dataclass
class Verdict:
    tool: str
    status: str  # pass | fail | skipped
    reason: str
    evidence: dict[str, Any] = field(default_factory=dict)


@dataclass
class CatalogProjection:
    marketplace_name: str
    files: dict[str, bytes]
    plugins: list[ProjectedPlugin]
    timestamp: int
    # version_id -> L0 verdicts
    verdicts: dict[str, list[Verdict]]
    # Public scope: per-plugin repositories (plugin_id -> files) for Gemini.
    plugin_repos: dict[str, dict[str, bytes]]
    excluded: list[dict[str, str]]


def _dump(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def _sha256(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def _slug(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return slug or "x"


def marketplace_name(scope_type: str, scope_id: str | None) -> str:
    """Stable marketplace identity (users type ``plugin@<name>``)."""
    if scope_type == "public":
        return "sessionfs"
    if scope_type == "org":
        return f"sessionfs-org-{_slug(scope_id or '')}"[:64].rstrip("-")
    if scope_type == "user":
        digest = hashlib.sha256((scope_id or "").encode("utf-8")).hexdigest()[:12]
        return f"sessionfs-user-{digest}"
    raise NativeFeedError(f"unknown catalog scope: {scope_type}")


def plugin_ids(inputs: list[CatalogInput]) -> dict[str, str]:
    """version_id -> plugin id ``<namespace>--<name>`` (kebab-case). Distinct
    packages that normalize to the same id get a deterministic suffix."""
    base: dict[str, str] = {}
    for item in inputs:
        base[item.version_id] = f"{_slug(item.namespace)}--{_slug(item.name)}"[:64].rstrip("-")
    counts: dict[str, int] = {}
    for value in base.values():
        counts[value] = counts.get(value, 0) + 1
    result: dict[str, str] = {}
    for item in inputs:
        value = base[item.version_id]
        if counts[value] > 1:
            suffix = hashlib.sha256(item.package_id.encode("utf-8")).hexdigest()[:8]
            value = f"{value[:55]}-{suffix}"
        result[item.version_id] = value
    return result


def projection_hash(files: dict[str, bytes]) -> str:
    """Digest of a plugin directory: sorted (path, content digest) pairs."""
    lines = "".join(f"{path}\0{_sha256(files[path])}\n" for path in sorted(files))
    return _sha256(lines.encode("utf-8"))


def _clean_text(value: str | None, limit: int) -> str:
    spaced = "".join(" " if ch in "\r\n\t" else ch for ch in (value or ""))
    text = "".join(ch for ch in spaced if ch == " " or ch.isprintable())
    return " ".join(text.split())[:limit]


def _check_reserved(path: str) -> None:
    parts = path.split("/")
    first = parts[0].casefold()
    if len(parts) > 1 and first in _RESERVED_FILE_NAMES:
        raise NativeFeedError(f"path uses a generated manifest name as a directory: {path}")
    if len(parts) == 1 and first in _RESERVED_DIR_NAMES:
        raise NativeFeedError(f"path uses a generated manifest directory name as a file: {path}")
    # Exact generated paths were already dropped; a case variant would
    # collide with the generated file on a case-insensitive checkout.
    if (len(parts) == 1 and first in _RESERVED_FILE_NAMES) or (
        len(parts) > 1 and first in _RESERVED_DIR_NAMES
    ):
        raise NativeFeedError(f"path collides with a generated manifest: {path}")


def _preflight(files: dict[str, bytes], plugin_id: str) -> None:
    """Everything that could make this plugin unwritable as part of a
    catalog tree, checked for the plugin alone."""
    if len(files) > MAX_PLUGIN_FILES:
        raise NativeFeedError(f"plugin has more than {MAX_PLUGIN_FILES} files")
    if sum(len(data) for data in files.values()) > MAX_PLUGIN_BYTES:
        raise NativeFeedError(f"plugin is larger than {MAX_PLUGIN_BYTES} bytes")
    try:
        check_tree(files)
        for path in files:
            validate_repo_path(f"plugins/{plugin_id}/{path}")
    except GitCatalogError as exc:
        raise NativeFeedError(str(exc)) from exc


def _plugin_files(item: CatalogInput, plugin_id: str, *, public: bool) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for path, data in item.files.items():
        if path in GENERATED_PLUGIN_FILES or path.startswith(_VENDOR_MANIFEST_DIRS):
            continue
        try:
            validate_repo_path(path)
        except GitCatalogError as exc:
            raise NativeFeedError(str(exc)) from exc
        _check_reserved(path)
        files[path] = data
    core: dict[str, Any] = {}
    raw_core = item.files.get("plugin.json")
    if raw_core is not None:
        try:
            parsed = json.loads(raw_core.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as exc:
            raise NativeFeedError("package plugin.json is not valid JSON") from exc
        if not isinstance(parsed, dict):
            raise NativeFeedError("package plugin.json is not an object")
        core = parsed
    description = _clean_text(item.description, 500)
    core["$schema"] = core.get("$schema") or AGENT_PLUGIN_SCHEMA
    core["name"] = plugin_id
    if item.version_label:
        core["version"] = item.version_label
    if description:
        core["description"] = description
    files["plugin.json"] = _dump(core)

    claude: dict[str, Any] = {"name": plugin_id}
    if item.version_label:
        claude["version"] = item.version_label
    if description:
        claude["description"] = description
    if item.publisher_name:
        claude["author"] = {"name": _clean_text(item.publisher_name, 200)}
    if item.homepage:
        claude["homepage"] = item.homepage
    if item.license:
        claude["license"] = _clean_text(item.license, 100)
    files[".claude-plugin/plugin.json"] = _dump(claude)
    files[".cursor-plugin/plugin.json"] = _dump({"name": plugin_id})
    if public:
        gemini: dict[str, Any] = {"name": plugin_id, "version": item.version_label or "0.0.0"}
        if description:
            gemini["description"] = description
        files["gemini-extension.json"] = _dump(gemini)
    _preflight(files, plugin_id)
    return files


# The longest plugin id ``plugin_ids`` can produce: admission checks use it
# so a path accepted here also fits under the real id.
_WORST_CASE_PLUGIN_ID = "x" * 64


def admission_size(item: CatalogInput, *, public: bool) -> int:
    """Bytes this input would take in a catalog (generated manifests
    included), or ``NativeFeedError`` when it would be excluded anyway.
    Lets a loader charge its byte budget only for plugins that can be
    admitted."""
    files = _plugin_files(item, _WORST_CASE_PLUGIN_ID, public=public)
    return sum(len(data) for data in files.values())


def _entry_common(plugin: ProjectedPlugin, item: CatalogInput) -> dict[str, Any]:
    entry: dict[str, Any] = {"name": plugin.plugin_id}
    description = _clean_text(item.description, 500)
    if description:
        entry["description"] = description
    if item.homepage:
        entry["homepage"] = item.homepage
    if item.license:
        entry["license"] = _clean_text(item.license, 100)
    return entry


def build_catalog(
    scope_type: str,
    scope_id: str | None,
    inputs: list[CatalogInput],
    *,
    description: str | None = None,
    max_files: int = DEFAULT_MAX_CATALOG_FILES,
    max_bytes: int = DEFAULT_MAX_CATALOG_BYTES,
    max_plugin_bytes: int = DEFAULT_MAX_ADMITTED_PLUGIN_BYTES,
    mirror: str | None = None,
) -> CatalogProjection:
    """Project approved versions into one catalog tree (deterministic).

    Never raises for one bad input: it is excluded with a reason. Inputs are
    admitted in ``BUDGET_ORDER`` while they fit ``max_files`` / ``max_bytes``
    (plugin files, generated manifests included).

    ``mirror`` (``owner/repo``, public scope only) adds the keyless GitHub
    mirror to README.md. Without it the bytes are exactly as before, so
    deployments that do not configure a mirror keep their commits."""
    name = marketplace_name(scope_type, scope_id)
    public = scope_type == "public"
    max_files = max(0, min(max_files, DEFAULT_MAX_CATALOG_FILES))
    ordered = sorted(inputs, key=lambda item: (item.namespace, item.name, item.version_id))
    ids = plugin_ids(ordered)
    plugins: list[ProjectedPlugin] = []
    excluded: list[dict[str, str]] = []
    by_version: dict[str, CatalogInput] = {}
    used_files = 0
    used_bytes = 0

    def exclude(item: CatalogInput, plugin_id: str, reason: str) -> None:
        excluded.append({"version_id": item.version_id, "plugin": plugin_id, "reason": reason[:300]})

    for item in ordered:
        plugin_id = ids[item.version_id]
        if item.skip_reason:
            exclude(item, plugin_id, item.skip_reason)
            continue
        try:
            files = _plugin_files(item, plugin_id, public=public)
        except NativeFeedError as exc:
            exclude(item, plugin_id, str(exc))
            continue
        size = sum(len(data) for data in files.values())
        if size > max_plugin_bytes:
            exclude(item, plugin_id, f"plugin_too_large: a catalog plugin is limited to {max_plugin_bytes} bytes")
            continue
        if used_files + len(files) > max_files or used_bytes + size > max_bytes:
            exclude(item, plugin_id, f"catalog_budget: the catalog is limited to {max_files} files "
                                     f"and {max_bytes} bytes")
            continue
        used_files += len(files)
        used_bytes += size
        tools = tuple(tool for tool in NATIVE_TOOLS if public or tool not in PUBLIC_ONLY_TOOLS)
        plugins.append(
            ProjectedPlugin(
                plugin_id=plugin_id,
                version_id=item.version_id,
                package_id=item.package_id,
                content_hash=item.content_hash,
                projection_hash=projection_hash(files),
                plugin_path=f"plugins/{plugin_id}",
                files=files,
                tools=tools,
            )
        )
        by_version[item.version_id] = item
    newest = max((item.published_at for item in by_version.values()), default=None)
    timestamp = int(_utc(newest).timestamp()) if newest is not None else 0
    catalog_version = (
        _utc(newest).strftime("%Y.%m.%d") + f".{len(plugins)}" if newest is not None else "0.0.0"
    )
    summary = _clean_text(description, 300) or f"SessionFS {scope_type} catalog (generated by SessionFS)"

    tree: dict[str, bytes] = {}
    for plugin in plugins:
        for path, data in plugin.files.items():
            tree[f"{plugin.plugin_path}/{path}"] = data

    claude_plugins = []
    copilot_plugins = []
    codex_plugins = []
    cursor_plugins = []
    for plugin in plugins:
        item = by_version[plugin.version_id]
        common = _entry_common(plugin, item)
        # version lives in plugin.json only (Claude Code warns when both set it)
        claude_plugins.append({**common, "source": f"./{plugin.plugin_path}"})
        copilot_plugins.append({**common, "source": f"./{plugin.plugin_path}"})
        codex_plugins.append(
            {
                "name": plugin.plugin_id,
                "source": {"source": "local", "path": f"./{plugin.plugin_path}"},
                "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                "category": CODEX_CATEGORY,
            }
        )
        cursor_plugins.append({**common, "source": plugin.plugin_path})
    metadata = {"description": summary, "version": catalog_version}
    tree[".claude-plugin/marketplace.json"] = _dump(
        {"name": name, "owner": OWNER, "description": summary, "metadata": metadata,
         "plugins": claude_plugins}
    )
    tree[".github/plugin/marketplace.json"] = _dump(
        {"name": name, "owner": OWNER, "metadata": metadata, "plugins": copilot_plugins}
    )
    tree[".agents/plugins/marketplace.json"] = _dump(
        {"name": name, "interface": {"displayName": summary[:100]}, "plugins": codex_plugins}
    )
    tree[".cursor-plugin/marketplace.json"] = _dump(
        {"name": name, "owner": OWNER, "metadata": metadata, "plugins": cursor_plugins}
    )
    tree["SESSIONFS-CATALOG.json"] = _dump(
        {
            "schema_version": 1,
            "generator_version": GENERATOR_VERSION,
            "scope": scope_type,
            "marketplace": name,
            "vendor_docs_checked": VENDOR_DOCS_CHECKED,
            "plugins": [
                {
                    "plugin": plugin.plugin_id,
                    "path": plugin.plugin_path,
                    "package_id": plugin.package_id,
                    "version_id": plugin.version_id,
                    "version": by_version[plugin.version_id].version_label,
                    "content_hash": plugin.content_hash,
                    "projection_hash": plugin.projection_hash,
                    "omitted_components": sorted(by_version[plugin.version_id].omitted_components),
                }
                for plugin in plugins
            ],
            "excluded": excluded,
            "budget": {"max_files": max_files, "max_bytes": max_bytes,
                       "max_plugin_bytes": max_plugin_bytes, "order": BUDGET_ORDER},
        }
    )
    readme = (
        f"# {name}\n\nGenerated by SessionFS. Do not edit: every commit is rebuilt from the "
        "approved package set.\n\nAdd it to your tool with `sfs catalog add --for <tool>`.\n"
    )
    if public and mirror:
        repo = parse_mirror(mirror)
        readme += (
            f"\nThis catalog is mirrored to https://github.com/{repo}, which needs no SessionFS "
            f"key:\n\n- Claude Code: `/plugin marketplace add {repo}`\n"
            f"- GitHub Copilot CLI: `copilot plugin marketplace add {repo}`\n"
            f"- Codex: `codex plugin marketplace add {repo}`\n"
            f"- Cursor: import https://github.com/{repo} as a team marketplace\n"
        )
    tree["README.md"] = readme.encode("utf-8")

    plugin_repos: dict[str, dict[str, bytes]] = {}
    if public:
        for plugin in plugins:
            plugin_repos[plugin.plugin_id] = dict(plugin.files)

    verdicts = {
        plugin.version_id: static_checks(tree, plugin, plugin_repos.get(plugin.plugin_id), public=public)
        for plugin in plugins
    }
    return CatalogProjection(
        marketplace_name=name,
        files=tree,
        plugins=plugins,
        timestamp=timestamp,
        verdicts=verdicts,
        plugin_repos=plugin_repos,
        excluded=excluded,
    )


def _utc(value: datetime) -> datetime:
    return value.replace(tzinfo=timezone.utc) if value.tzinfo is None else value.astimezone(timezone.utc)


