def _load(tree: dict[str, bytes], path: str) -> Any:
    raw = tree.get(path)
    if raw is None:
        raise NativeFeedError(f"missing {path}")
    try:
        return json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        raise NativeFeedError(f"{path} is not valid JSON") from exc


def _entry(catalog: Any, plugin_id: str, path: str) -> dict:
    if not isinstance(catalog, dict) or not isinstance(catalog.get("plugins"), list):
        raise NativeFeedError(f"{path}: plugins must be a list")
    matches = [item for item in catalog["plugins"] if isinstance(item, dict) and item.get("name") == plugin_id]
    if len(matches) != 1:
        raise NativeFeedError(f"{path}: expected exactly one entry named {plugin_id}")
    return matches[0]


def _has_dir(tree: dict[str, bytes], directory: str) -> bool:
    prefix = directory.rstrip("/") + "/"
    return any(path.startswith(prefix) for path in tree)


def _skill_dirs(files: dict[str, bytes]) -> list[str]:
    return sorted({path.rsplit("/", 1)[0] for path in files if re.fullmatch(r"skills/[^/]+/SKILL\.md", path)})


def _frontmatter(text: str) -> dict[str, Any]:
    from sessionfs.skills.disclosure import _frontmatter as parse

    return parse(text)


def _check_claude(tree: dict[str, bytes], plugin: ProjectedPlugin) -> list[str]:
    problems: list[str] = []
    catalog = _load(tree, ".claude-plugin/marketplace.json")
    name = catalog.get("name") if isinstance(catalog, dict) else None
    if not isinstance(name, str) or not _CLAUDE_MARKETPLACE_NAME.match(name) or ".." in name:
        problems.append("marketplace name is not valid")
    owner = catalog.get("owner") if isinstance(catalog, dict) else None
    if not isinstance(owner, dict) or not isinstance(owner.get("name"), str):
        problems.append("owner.name is required")
    entry = _entry(catalog, plugin.plugin_id, ".claude-plugin/marketplace.json")
    source = entry.get("source")
    if not isinstance(source, str) or not source.startswith("./") or ".." in source:
        problems.append("relative source must start with ./ and must not contain ..")
    elif not _has_dir(tree, source[2:]):
        problems.append(f"source {source} does not exist in the catalog")
    if not _KEBAB.match(plugin.plugin_id):
        problems.append("plugin name must be kebab-case")
    if plugin.plugin_id.startswith(_CLAUDE_RESERVED_PREFIXES) or _CLAUDE_OFFICIAL.search(plugin.plugin_id):
        problems.append("plugin name is reserved by Claude Code (claude-/anthropic-/cc-plugin- prefix)")
    manifest = _load(tree, f"{plugin.plugin_path}/.claude-plugin/plugin.json")
    if not isinstance(manifest, dict) or manifest.get("name") != plugin.plugin_id:
        problems.append(".claude-plugin/plugin.json name must match the catalog entry")
    elif "version" in manifest and "version" in entry:
        problems.append("version must be set in only one place")
    return problems


def _check_copilot(tree: dict[str, bytes], plugin: ProjectedPlugin) -> list[str]:
    problems: list[str] = []
    catalog = _load(tree, ".github/plugin/marketplace.json")
    owner = catalog.get("owner") if isinstance(catalog, dict) else None
    if not isinstance(catalog.get("name"), str) or not isinstance(owner, dict) or "name" not in owner:
        problems.append("name and owner.name are required")
    entry = _entry(catalog, plugin.plugin_id, ".github/plugin/marketplace.json")
    source = entry.get("source")
    relative = source[2:] if isinstance(source, str) and source.startswith("./") else source
    if not isinstance(relative, str) or ".." in relative or not _has_dir(tree, relative):
        problems.append("source must be a relative path to a plugin directory in the catalog")
    core = _load(tree, f"{plugin.plugin_path}/plugin.json")
    if not isinstance(core, dict) or not core.get("$schema") or core.get("name") != plugin.plugin_id:
        problems.append("root plugin.json needs $schema and a name matching the entry (Agent Plugins format)")
    return problems


def _check_codex(tree: dict[str, bytes], plugin: ProjectedPlugin) -> list[str]:
    problems: list[str] = []
    catalog = _load(tree, ".agents/plugins/marketplace.json")
    if not isinstance(catalog.get("name"), str):
        problems.append("name is required")
    entry = _entry(catalog, plugin.plugin_id, ".agents/plugins/marketplace.json")
    source = entry.get("source")
    if not (
        isinstance(source, dict)
        and source.get("source") == "local"
        and isinstance(source.get("path"), str)
        and source["path"].startswith("./")
        and ".." not in source["path"]
        and _has_dir(tree, source["path"][2:])
    ):
        problems.append("source must be a local ./ path to a plugin directory in the catalog")
    policy = entry.get("policy")
    if not isinstance(policy, dict) or policy.get("installation") not in {
        "AVAILABLE", "INSTALLED_BY_DEFAULT", "NOT_AVAILABLE"
    }:
        problems.append("policy.installation is required")
    if not isinstance(entry.get("category"), str):
        problems.append("category is required")
    if not _KEBAB.match(plugin.plugin_id):
        problems.append("plugin name must be kebab-case")
    core = _load(tree, f"{plugin.plugin_path}/plugin.json")
    if not isinstance(core, dict) or core.get("name") != plugin.plugin_id:
        problems.append("plugin.json name must match the catalog entry")
    return problems


def _check_cursor(tree: dict[str, bytes], plugin: ProjectedPlugin) -> list[str]:
    problems: list[str] = []
    raw = tree.get(".cursor-plugin/marketplace.json", b"")
    if len(raw) > 10 * 1024 * 1024:
        problems.append("marketplace.json exceeds 10 MB")
    catalog = _load(tree, ".cursor-plugin/marketplace.json")
    name = catalog.get("name")
    if not isinstance(name, str) or not _CURSOR_NAME.match(name):
        problems.append("marketplace name must be lowercase kebab-case")
    owner = catalog.get("owner")
    if not isinstance(owner, dict) or "name" not in owner:
        problems.append("owner.name is required")
    entry = _entry(catalog, plugin.plugin_id, ".cursor-plugin/marketplace.json")
    source = entry.get("source")
    if not isinstance(source, str) or ".." in source or not _has_dir(tree, source.removeprefix("./")):
        problems.append("source must be a relative path to a plugin directory in the catalog")
    if not _CURSOR_NAME.match(plugin.plugin_id):
        problems.append("plugin name must be lowercase alphanumerics, - and .")
    manifest = _load(tree, f"{plugin.plugin_path}/.cursor-plugin/plugin.json")
    if not isinstance(manifest, dict) or manifest.get("name") != plugin.plugin_id:
        problems.append(".cursor-plugin/plugin.json name must match the catalog entry")
    return problems


def _check_gemini(repo: dict[str, bytes] | None, plugin: ProjectedPlugin) -> list[str]:
    if repo is None:
        return ["no per-plugin repository"]
    problems: list[str] = []
    manifest = _load(repo, "gemini-extension.json")
    if not isinstance(manifest, dict) or manifest.get("name") != plugin.plugin_id:
        problems.append("gemini-extension.json name must match the extension")
    elif not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", plugin.plugin_id.replace("--", "-")):
        problems.append("extension name must be lowercase with dashes")
    for skill_dir in _skill_dirs(repo):
        if not _frontmatter(repo[f"{skill_dir}/SKILL.md"].decode("utf-8", "replace")).get("description"):
            problems.append(f"{skill_dir}/SKILL.md has no description")
    return problems


def _check_antigravity(files: dict[str, bytes], plugin: ProjectedPlugin) -> list[str]:
    problems: list[str] = []
    core = _load(files, "plugin.json")
    if not isinstance(core, dict) or not isinstance(core.get("name"), str) or not _ANTIGRAVITY_NAME.match(core["name"]):
        problems.append("plugin.json name must be letters, digits, - or _")
    skills = _skill_dirs(files)
    for skill_dir in skills:
        if not _frontmatter(files[f"{skill_dir}/SKILL.md"].decode("utf-8", "replace")).get("description"):
            problems.append(f"{skill_dir}/SKILL.md has no description (required by Antigravity)")
    return problems


def static_checks(
    tree: dict[str, bytes],
    plugin: ProjectedPlugin,
    plugin_repo: dict[str, bytes] | None,
    *,
    public: bool,
) -> list[Verdict]:
    """L0 verdict per native tool for one projected plugin."""
    checks = {
        "claude-code": lambda: _check_claude(tree, plugin),
        "copilot": lambda: _check_copilot(tree, plugin),
        "codex": lambda: _check_codex(tree, plugin),
        "cursor": lambda: _check_cursor(tree, plugin),
        "gemini": lambda: _check_gemini(plugin_repo, plugin),
        "antigravity": lambda: _check_antigravity(plugin.files, plugin),
    }
    verdicts: list[Verdict] = []
    for tool in NATIVE_TOOLS:
        if tool in PUBLIC_ONLY_TOOLS and not public:
            verdicts.append(Verdict(tool, "skipped", "public mirror only (Gemini installs public repositories)"))
            continue
        try:
            problems = checks[tool]()
        except NativeFeedError as exc:
            problems = [str(exc)]
        evidence = {
            "projection_hash": plugin.projection_hash,
            "generator_version": GENERATOR_VERSION,
            "vendor_docs_checked": VENDOR_DOCS_CHECKED,
        }
        if problems:
            verdicts.append(Verdict(tool, "fail", "; ".join(problems)[:1000], evidence))
        else:
            verdicts.append(Verdict(tool, "pass", "projection matches the documented format", evidence))
    return verdicts
